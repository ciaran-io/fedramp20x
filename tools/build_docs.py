#!/usr/bin/env python3
"""Generate docs/rules-matrix.md: every FedRAMP Consolidated Rule (FRR) that
applies to a 20x Class C certification, with the party each rule addresses, straight from the vendored FRMR data.

Each row gets a response status from docs/rule-responses.json when that file exists
(rule id -> {status, owner, doc}). Unlisted rules show as `unassessed`, never as
compliant. This is the backbone for the Security Decision Record.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLS, TYPE = "C", "20x"


def applies(sub_info: dict) -> bool:
    a = (sub_info or {}).get("applicability", {})
    if a.get("types") and TYPE not in a["types"]:
        return False
    if a.get("classes") and CLS not in a["classes"]:
        return False
    return True


def parties(req: dict, sub_info: dict) -> list:
    """Who a rule is addressed to: Providers, Agencies, FedRAMP (the Program), Assessors or Advisors."""
    a = req.get("affects")
    if not a and req.get("varies_by_class"):
        a = next(iter(req["varies_by_class"].values())).get("affects")
    return list(a or (sub_info or {}).get("applicability", {}).get("affects") or ["Providers"])


def resolve(req: dict):
    """Return (statement, force) for Class C, or None if not applicable."""
    v = req.get("varies_by_class")
    if v:
        c = v.get(CLS.lower())
        return (c["statement"], c.get("force", "")) if c else None
    return req.get("statement", ""), req.get("force", "")


def main() -> None:
    d = json.loads((ROOT / "frmr/fedramp-consolidated-rules.json").read_text())
    resp_path = ROOT / "docs/rule-responses.json"
    responses = json.loads(resp_path.read_text()) if resp_path.exists() else {}
    rows, counts = [], {}
    for proc, body in d["FRR"].items():
        info = body.get("info", {})
        for bucket in ("all", TYPE):
            subsets_info = {**info.get("subsets", {}), **info.get(bucket, {}).get("subsets", {})} if bucket != "all" else info.get("subsets", {})
            for sub, reqs in body.get("data", {}).get(bucket, {}).items():
                if subsets_info and sub in subsets_info and not applies(subsets_info[sub]):
                    continue
                for rid, req in reqs.items():
                    r = resolve(req)
                    if not r:
                        continue
                    stmt, force = r
                    resp = responses.get(rid, {})
                    status = resp.get("status", "unassessed")
                    counts[status] = counts.get(status, 0) + 1
                    rows.append((proc, rid, req.get("name", ""), force, status, resp.get("owner", ""), resp.get("doc", ""), stmt, parties(req, subsets_info.get(sub))))
    rows.sort(key=lambda r: r[:8])
    by_party: dict = {}
    for r in rows:
        for w in r[8]:
            by_party[w] = by_party.get(w, 0) + 1
    out = [
        "# Rules matrix: 20x Class C",
        "",
        f"> FICTIONAL DEMO. Source: FRMR `{d['info']['version']}` (see `frmr/PROVENANCE.md`). Generated by `tools/build_docs.py`; do not edit.",
        "> Status comes from `docs/rule-responses.json`. Without that file every rule is `unassessed`.",
        "",
        "Summary: " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())) + f" ({len(rows)} rules)",
        "",
        "Rules by party: " + ", ".join(f"{k}: {v}" for k, v in sorted(by_party.items())) + ". The trust center Rules tab filters by party.",
        "",
        "| Process | Rule | Name | Addressed to | Force | Status | Owner | Response doc |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for proc, rid, name, force, status, owner, doc, _, who in rows:
        out.append(f"| {proc} | `{rid}` | {name} | {', '.join(who)} | {force} | {status} | {owner} | {doc} |")
    (ROOT / "docs/rules-matrix.md").write_text("\n".join(out) + "\n")
    (ROOT / "evidence/rules-matrix.json").write_text(json.dumps(
        [{"process": p, "id": i, "name": n, "force": f, "affects": w, "status": s, "owner": o, "doc": dc}
         for p, i, n, f, s, o, dc, st, w in rows], indent=1) + "\n")
    print(f"wrote docs/rules-matrix.md: {len(rows)} rules", counts)


if __name__ == "__main__":
    main()
