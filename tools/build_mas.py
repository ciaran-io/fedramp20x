#!/usr/bin/env python3
"""Validate mas/mas-record.json and render the human-readable scope document.

  mas/mas-record.json  (source of truth, edit this)
        |  schema check + consistency checks
        v
  docs/minimum-assessment-scope.md   generated, do not edit
  docs/diagrams/mas-data-flows.drawio + three SVGs   generated by build_mas_diagram.py
  evidence/mas-summary.json          counts, condition register and prohibited flows for validators

Usage: build_mas.py [--check] [path/to/record.json]
Exit status is non-zero when any ERROR is found. WARN and INFO lines are advisory.
"""
import json
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

try:
    import jsonschema
except ImportError:
    sys.exit("pip install jsonschema")

ROOT = Path(__file__).resolve().parent.parent
LV = {"Low": 0, "Moderate": 1, "High": 2}
NAME = {v: k for k, v in LV.items()}
CIA = ("confidentiality", "integrity", "availability")
SENSITIVE = {"D1", "D2", "D3", "D4", "D7", "D8", "D10"}  # must not flow to excluded resources
DECISION_LABEL = {"in_scope": "In scope", "third_party": "Third party (TPR)", "out_of_scope": "Out",
                  "out_conditional": "Out, conditional", "supplement": "Supplement"}


def load(path=None):
    rec = json.loads(Path(path or ROOT / "mas/mas-record.json").read_text())
    schema = json.loads((ROOT / "schemas/mas-record.schema.json").read_text())
    return rec, schema


def hi(a, b):
    return NAME[max(LV[a], LV[b])]


# --------------------------------------------------------------------------- checks
def check(rec):
    msgs = []  # (level, text)
    err = lambda t: msgs.append(("ERROR", t))
    warn = lambda t: msgs.append(("WARN", t))
    info = lambda t: msgs.append(("INFO", t))

    # official dataset pin
    frmr = json.loads((ROOT / "frmr/fedramp-consolidated-rules.json").read_text())
    if rec["frmr_version"] != frmr["info"]["version"]:
        warn(f"record pinned to FRMR {rec['frmr_version']} but frmr/ holds {frmr['info']['version']}; review for rule changes")
    for rid in ("MAS-CSO-IIR", "MAS-CSO-FLO", "MAS-CSO-TPR", "MAS-CSO-MDI", "MAS-CSO-SUP"):
        if rid not in json.dumps(frmr["FRR"]["MAS"]):
            err(f"{rid} not found in the downloaded FRMR data")

    zones = {z["id"]: z for z in rec["trust_zones"]}
    ext = {e["id"]: e for e in rec["external_entities"]}
    dcs = {d["id"]: d for d in rec["data_classes"]}
    res = {r["id"]: r for r in rec["information_resources"]}
    flows = rec["information_flows"]

    # unique ids
    for label, items in (("resource", rec["information_resources"]), ("flow", flows), ("data class", rec["data_classes"]),
                         ("prohibited flow", rec["prohibited_flows"]), ("TPR", rec["third_party_resources"]),
                         ("metadata", rec["metadata_inclusion"]), ("zone", rec["trust_zones"]), ("external", rec["external_entities"])):
        dup = [k for k, v in Counter(i["id"] for i in items).items() if v > 1]
        if dup:
            err(f"duplicate {label} ids: {dup}")
    clash = set(res) & set(ext)
    if clash:
        err(f"ids used as both resource and external entity: {sorted(clash)}")
    endpoints = set(res) | set(ext)

    def known_dc(where, ids):
        for d in ids:
            if d not in dcs:
                err(f"{where}: unknown data class {d}")

    # zones and decisions
    for r in rec["information_resources"]:
        z = zones.get(r["zone"])
        if not z:
            err(f"{r['id']}: unknown zone {r['zone']}")
            continue
        if r["decision"] == "in_scope" and not z["in_cso"]:
            err(f"{r['id']}: in_scope but zone {z['id']} is outside the CSO")
        if r["decision"] != "in_scope" and z["in_cso"]:
            err(f"{r['id']}: decision {r['decision']} but zone {z['id']} is inside the CSO")
        known_dc(r["id"], r["handles"] + r.get("may_hold", []))
        if r["decision"] in ("out_of_scope", "out_conditional", "supplement") and r["handles"]:
            err(f"{r['id']}: excluded ({r['decision']}) but handles {r['handles']}; if it handles data it cannot be out")
        if r["decision"] == "out_of_scope" and r.get("may_hold"):
            err(f"{r['id']}: out_of_scope but may hold {r['may_hold']}; make it out_conditional with conditions")
        if r["decision"] == "out_conditional" and not r.get("conditions"):
            err(f"{r['id']}: out_conditional needs at least one condition")
        for c in r.get("conditions", []):
            if not c["id"].startswith(f"COND-{r['id']}-"):
                err(f"{c['id']}: condition id must start with COND-{r['id']}-")
        if r["decision"] != "out_conditional" and r.get("conditions"):
            warn(f"{r['id']}: has conditions but decision is {r['decision']}")
        if r["decision"] == "in_scope":
            if not r["handles"] and "security_category" not in r:
                err(f"{r['id']}: in scope with no data classes needs an explicit security_category")
        for p in r.get("performed_via", []):
            if p not in res or res[p]["decision"] not in ("in_scope", "third_party"):
                err(f"{r['id']}: performed_via {p} is not an in-scope or third-party resource")
        if r["kind"] == "non_machine_based" and r["decision"] == "in_scope" and "performed_via" not in r and r["id"] not in ("N4", "N5", "N6"):
            info(f"{r['id']}: non-machine resource without performed_via links")

    # effective security categories
    eff = {}
    for r in rec["information_resources"]:
        if r["decision"] not in ("in_scope", "third_party"):
            continue
        derived = {k: "Low" for k in CIA}
        for d in r["handles"]:
            for k in CIA:
                derived[k] = hi(derived[k], dcs[d]["security_category"][k])
        declared = r.get("security_category")
        if declared and r["handles"]:
            for k in CIA:
                if LV[declared[k]] < LV[derived[k]]:
                    err(f"{r['id']}: declared {k} {declared[k]} is below {derived[k]} derived from the data it handles")
        final = dict(derived)
        if declared:
            final = {k: hi(derived[k], declared[k]) for k in CIA}
        eff[r["id"]] = {"category": final, "source": "declared" if declared and not r["handles"] else ("derived" if not declared else "declared+derived")}

    # flows
    touched = set()
    cond_ids = {c["id"]: r["id"] for r in rec["information_resources"] for c in r.get("conditions", [])}
    for f in flows:
        for end in ("source", "destination"):
            if f[end] not in endpoints:
                err(f"{f['id']}: unknown {end} {f[end]}")
        touched |= {f["source"], f["destination"]}
        known_dc(f["id"], f["data_classes"])
        if f["type"] == "control" and f["data_classes"]:
            err(f"{f['id']}: control flow must not list data classes")
        if f["type"] == "data" and not f["data_classes"] and not f.get("conditional_on"):
            warn(f"{f['id']}: data flow with no data classes")
        dest = res.get(f["destination"])
        if dest and dest["decision"] in ("out_of_scope", "out_conditional", "supplement"):
            if dest["decision"] == "out_of_scope":
                err(f"{f['id']}: flows to out_of_scope resource {dest['id']}")
            conds = f.get("conditional_on", [])
            if not conds or any(cond_ids.get(c) != dest["id"] for c in conds):
                err(f"{f['id']}: flows to excluded resource {dest['id']} without a condition belonging to it")
            if set(f["data_classes"]) & SENSITIVE:
                err(f"{f['id']}: carries {sorted(set(f['data_classes']) & SENSITIVE)} to excluded resource {dest['id']}")
        for c in f.get("conditional_on", []):
            if c not in cond_ids:
                err(f"{f['id']}: unknown condition {c}")
        if {"D4", "D7"} & set(f["data_classes"]) and "TLS" not in f["encryption_in_transit"]:
            err(f"{f['id']}: carries D4 or D7 without TLS in encryption_in_transit")
        if dest and dest["id"] in ("T1", "T2", "T3") and "D4" in f["data_classes"]:
            err(f"{f['id']}: payload policy violation, D4 flows to notification provider {dest['id']}")

    for r in rec["information_resources"]:
        if r["decision"] in ("in_scope", "third_party") and r["kind"] == "machine_based" and r["id"] not in touched:
            warn(f"{r['id']}: in scope but appears in no information flow")

    # data class coverage
    handled = {d for r in res.values() if r["decision"] in ("in_scope", "third_party") for d in r["handles"]}
    in_flows = {d for f in flows for d in f["data_classes"]}
    for d in dcs:
        if d not in handled:
            info(f"{d} ({dcs[d]['name']}) is handled by no in-scope or third-party resource; it relies entirely on exclusion conditions")
        if d not in in_flows:
            info(f"{d} appears in no information flow")

    # prohibited flows must cover every conditional exclusion that may hold data
    pf_to = {t for p in rec["prohibited_flows"] for t in p["to"]}
    pf_from = {t for p in rec["prohibited_flows"] for t in p["from"]}
    for p in rec["prohibited_flows"]:
        for e in p["from"] + p["to"]:
            if e not in res:
                err(f"{p['id']}: unknown resource {e}")
        known_dc(p["id"], p["data_classes"])
    for r in res.values():
        if r["decision"] == "out_conditional" and r.get("may_hold") and r["id"] not in pf_to | pf_from:
            warn(f"{r['id']}: conditional exclusion that may hold data is not covered by any prohibited flow")

    # third parties
    tprs = {t["resource_id"]: t for t in rec["third_party_resources"]}
    for r in res.values():
        if r["decision"] == "third_party" and r["id"] not in tprs:
            err(f"{r['id']}: third_party resource has no TPR record (MAS-CSO-TPR)")
    for rid in tprs:
        if rid not in res or res[rid]["decision"] != "third_party":
            err(f"TPR for {rid}: resource is missing or not marked third_party")

    # supplement
    sup = {i["resource_id"] for i in rec["supplement"]["items"]}
    for r in res.values():
        if r["decision"] == "supplement" and r["id"] not in sup:
            err(f"{r['id']}: supplement resource missing from supplement items")
    for s in sup:
        if s not in res or res[s]["decision"] != "supplement":
            err(f"supplement item {s}: resource missing or not marked supplement")

    # metadata inclusion
    for m in rec["metadata_inclusion"]:
        for s in m["stored_in"]:
            if s not in res:
                err(f"{m['id']}: unknown resource {s}")
            elif res[s]["decision"] not in ("in_scope", "third_party"):
                err(f"{m['id']}: metadata stored in {s}, which is outside the offering (MAS-CSO-MDI)")
        if m.get("data_class") and m["data_class"] not in dcs:
            err(f"{m['id']}: unknown data class {m['data_class']}")

    return msgs, eff


# --------------------------------------------------------------------------- rendering
def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def cat_str(c):
    return "/".join(NAME[LV[c[k]]][0] for k in CIA)


def mermaid(rec):
    res = {r["id"]: r for r in rec["information_resources"]}
    ext = {e["id"]: e for e in rec["external_entities"]}
    data_flows = [f for f in rec["information_flows"] if f["type"] == "data"]
    used = {x for f in data_flows for x in (f["source"], f["destination"])}
    zname = {z["id"]: z["name"] for z in rec["trust_zones"]}
    groups = {}
    for i in sorted(used, key=lambda s: (s[0], int(''.join(c for c in s if c.isdigit())))):
        z = (res.get(i) or ext.get(i))["zone"]
        groups.setdefault(z, []).append(i)
    def short(t):
        t = t.split(" (")[0].replace('"', "'")
        words, lines, cur = t.split(), [], ""
        for w_ in words:
            if cur and len(cur) + len(w_) + 1 > 22:
                lines.append(cur)
                cur = w_
            else:
                cur = (cur + " " + w_).strip()
        lines.append(cur)
        return "<br/>".join(lines)
    out = ["flowchart TB"]
    for z in [z["id"] for z in rec["trust_zones"] if z["id"] in groups]:
        out.append(f'  subgraph {z.replace("-", "_")}["{zname[z]}"]')
        for i in groups[z]:
            n = res.get(i) or ext.get(i)
            out.append(f'    {i}["{i} {short(n["name"])}"]')
        out.append("  end")
    for f in data_flows:
        style = "-.->" if f.get("conditional_on") else "-->"
        out.append(f'  {f["source"]} {style}|{f["id"]}| {f["destination"]}')
    for i in used:
        d = (res.get(i) or {}).get("decision")
        if d == "third_party":
            out.append(f"  style {i} stroke-dasharray: 4 3")
        if d == "out_conditional":
            out.append(f"  style {i} stroke-dasharray: 2 2,stroke:#b26a00")
    return "\n".join(out) + "\n"


def render(rec, eff, msgs):
    res = {r["id"]: r for r in rec["information_resources"]}
    dcs = {d["id"]: d for d in rec["data_classes"]}
    by = lambda dec: [r for r in rec["information_resources"] if r["decision"] == dec]
    counts = Counter(r["decision"] for r in rec["information_resources"])
    inscope = by("in_scope")
    hwm = {k: "Low" for k in CIA}
    for r in inscope:
        for k in CIA:
            hwm[k] = hi(hwm[k], eff[r["id"]]["category"][k])

    o = []
    w = o.append
    w(f"# Minimum Assessment Scope: {rec['cso']['name']}")
    w("")
    w("> **FICTIONAL DEMO DOCUMENT.** Orrinwick Labs, Inc. is invented. **Generated** from `mas/mas-record.json` by `tools/build_mas.py`. Edit the JSON, not this file.")
    w("")
    w("| | |")
    w("|---|---|")
    w(f"| Offering | {rec['cso']['name']} ({rec['cso']['provider']}) |")
    w(f"| Target | FedRAMP 20x Class {rec['cso']['target_class'].upper()} |")
    w(f"| Record version / status | {rec['record_version']} / {rec['status']} |")
    w(f"| FRMR dataset | {rec['frmr_version']} |")
    w(f"| Overview | `{rec['cso'].get('overview_doc', '')}` |")
    w("")
    w("## 1. Summary")
    w("")
    w(f"The cloud service offering is the set of **{counts['in_scope']} in-scope information resources** "
      f"({sum(1 for r in inscope if r['kind']=='machine_based')} machine-based, {sum(1 for r in inscope if r['kind']=='non_machine_based')} people and process). "
      f"Beyond that: {counts['third_party']} third-party resources are documented, {counts['out_conditional']} are excluded only on stated conditions, "
      f"{counts['out_of_scope']} are excluded outright and {counts['supplement']} is a supplement item.")
    w("")
    w(f"**Highest security category across in-scope resources (confidentiality / integrity / availability): {hwm['confidentiality']} / {hwm['integrity']} / {hwm['availability']}.** "
      "Levels are preliminary working labels (see open question OQ6).")
    w("")
    w("| Rule | Requirement in short | Where addressed |")
    w("|---|---|---|")
    w("| `MAS-CSO-IIR` | List the information resources that may touch federal customer data | Sections 2 and 3 |")
    w("| `MAS-CSO-FLO` | Document and explain information flows and security categories for all resources | Sections 4 and 5 |")
    w("| `MAS-CSO-MDI` | Include metadata, including metadata about federal customer data | Section 6 |")
    w("| `MAS-CSO-TPR` | Document third-party resources: usage, justification, mitigations, compensating controls | Section 7 |")
    w("| `MAS-CSO-SUP` | Optionally supplement; clearly separated and not certified | Section 8 |")
    w("")
    w("### How decisions are made")
    w("")
    w("A resource is **in scope** if it may handle federal customer data **or** may affect its confidentiality, integrity or availability. "
      "Information resources include people, policies and procedures as well as technology. A resource is excluded only with a stated reason; "
      "where it could plausibly end up holding data, it is excluded **only on named conditions** that must be evidenced (section 9).")
    w("")
    w("## 2. Information resources (MAS-CSO-IIR)")
    w("")
    w("Security category shown as confidentiality/integrity/availability (L, M, H). *Derived* means the maximum of the data classes the resource handles; *declared* is set where the resource holds no data but affects it.")
    w("")
    groups = ["Production service", "Engineering and operations", "People and processes", "Support and corporate IT"]
    for g in groups:
        rows = [r for r in inscope if r["group"] == g]
        if not rows:
            continue
        w(f"### 2.{groups.index(g)+1} In scope: {g}")
        w("")
        w("| ID | Resource | Type | Handles | Category | Why it is in scope |")
        w("|---|---|---|---|---|---|")
        for r in rows:
            e = eff[r["id"]]
            w(f"| {r['id']} | {esc(r['name'])} | {'machine' if r['kind']=='machine_based' else 'people / process'} | {', '.join(r['handles']) or 'none'} | {cat_str(e['category'])} ({e['source']}) | {esc(r.get('impact_on_fcd') or r['rationale'])} |")
        w("")
    w("### 2.5 Third-party resources in the data path")
    w("")
    w("| ID | Resource | Handles | Rationale |")
    w("|---|---|---|---|")
    for r in by("third_party"):
        w(f"| {r['id']} | {esc(r['name'])} | {', '.join(r['handles'])} | {esc(r['rationale'])} |")
    w("")
    w("### 2.6 Excluded, with conditions")
    w("")
    w("These stay out **only while their conditions hold**. If a condition cannot be evidenced, the resource moves in scope.")
    w("")
    w("| ID | Resource | Could hold | Conditions |")
    w("|---|---|---|---|")
    for r in by("out_conditional"):
        w(f"| {r['id']} | {esc(r['name'])} | {', '.join(r.get('may_hold', []))} | {' '.join(c['id'] for c in r['conditions'])} |")
    w("")
    w("### 2.7 Excluded outright")
    w("")
    w("| ID | Resource | Why it is out |")
    w("|---|---|---|")
    for r in by("out_of_scope"):
        w(f"| {r['id']} | {esc(r['name'])} | {esc(r['rationale'])} |")
    w("")
    w("## 3. Federal customer data and metadata")
    w("")
    w("The official definition of federal customer data **excludes** account information, service metadata, analytics and telemetry generated by the provider. "
      "Those are still included in scope as metadata (section 6). \"Mixed\" classes contain both kinds.")
    w("")
    w("| ID | Class | Federal customer data? | Basis | Category (C/I/A) | Where it can live |")
    w("|---|---|---|---|---|---|")
    for d in rec["data_classes"]:
        where = [r["id"] for r in rec["information_resources"] if d["id"] in r["handles"]]
        may = [r["id"] for r in rec["information_resources"] if d["id"] in r.get("may_hold", [])]
        loc = ", ".join(where) + (f" (possible: {', '.join(may)})" if may else "")
        w(f"| {d['id']} | {esc(d['name'])} | {d['federal_customer_data']} | {esc(d['fcd_basis'])} | {cat_str(d['security_category'])} | {loc} |")
    w("")
    w("## 4. Information flows (MAS-CSO-FLO)")
    w("")
    w("Data flows only; control flows are in the table below. Orange dotted edges exist only while their conditions hold; red dashed edges are prohibited flows. The editable source is `docs/diagrams/mas-data-flows.drawio` (three pages).")
    w("")
    for title, f in (("Alert and notification path", "mas-alert-path"), ("Storage, operations and privileged access", "mas-operations"), ("Conditional and prohibited flows", "mas-boundary")):
        w(f"![{title}](diagrams/{f}.svg)")
        w("")
    w("### Network architecture (design assumption)")
    w("")
    w("Where the in-scope resources live. AWS and Terraform are a fictional design choice added for this project; the record itself is vendor-neutral. Source: `docs/diagrams/network-architecture.drawio`.")
    w("")
    w("![Network architecture](diagrams/network-architecture.svg)")
    w("")
    w("")
    w("### 4.1 Trust zones")
    w("")
    w("| Zone | In the offering | Description |")
    w("|---|---|---|")
    for z in rec["trust_zones"]:
        w(f"| {z['id']} {esc(z['name'])} | {'yes' if z['in_cso'] else 'no'} | {esc(z['description'])} |")
    w("")
    w("### 4.2 External entities")
    w("")
    w("| ID | Entity | Description |")
    w("|---|---|---|")
    for e in rec["external_entities"]:
        w(f"| {e['id']} | {esc(e['name'])} | {esc(e['description'])} |")
    w("")
    nm = lambda i: f"{i} {esc((res.get(i) or {}).get('name') or next(e['name'] for e in rec['external_entities'] if e['id']==i))}"
    for typ, title in (("data", "4.3 Data flows"), ("control", "4.4 Control flows")):
        w(f"### {title}")
        w("")
        w("| ID | Flow | From | To | Data | Protocol and authentication | Notes |")
        w("|---|---|---|---|---|---|---|")
        for f in rec["information_flows"]:
            if f["type"] != typ:
                continue
            cond = f" Only while {', '.join(f['conditional_on'])} holds." if f.get("conditional_on") else ""
            w(f"| {f['id']} | {esc(f['name'])} | {nm(f['source'])} | {nm(f['destination'])} | {', '.join(f['data_classes']) or 'none'} | {esc(f['protocol'])}; {esc(f['authentication'])}; {esc(f['encryption_in_transit'])} | {esc(f['description'])}{cond} |")
        w("")
    w("### 4.5 Prohibited flows")
    w("")
    w("Data that must **not** move between these resources. Each is the basis of an exclusion and a candidate automated check.")
    w("")
    w("| ID | Prohibited flow | From | To | Data | Control | Evidence |")
    w("|---|---|---|---|---|---|---|")
    for p in rec["prohibited_flows"]:
        w(f"| {p['id']} | {esc(p['name'])} | {', '.join(p['from'])} | {', '.join(p['to'])} | {', '.join(p['data_classes'])} | {esc(p['control'])} | {esc(p['evidence'])} |")
    w("")
    w("## 5. Security categories")
    w("")
    w("Per-resource categories are in section 2; per-data-class categories are in section 3. Rationale per data class:")
    w("")
    w("| Class | Rationale |")
    w("|---|---|")
    for d in rec["data_classes"]:
        w(f"| {d['id']} {esc(d['name'])} | {esc(d['category_rationale'])} |")
    w("")
    w("Resources rated by privilege rather than data:")
    w("")
    w("| Resource | Category | Rationale |")
    w("|---|---|---|")
    for r in inscope:
        if r.get("category_rationale"):
            w(f"| {r['id']} {esc(r['name'])} | {cat_str(eff[r['id']]['category'])} | {esc(r['category_rationale'])} |")
    w("")
    w("## 6. Metadata (MAS-CSO-MDI)")
    w("")
    w("| ID | Metadata | Generated by | About | Stored in | Note |")
    w("|---|---|---|---|---|---|")
    for m in rec["metadata_inclusion"]:
        w(f"| {m['id']} | {esc(m['metadata_type'])} | {esc(m['generated_by'])} | {esc(m['about'])} | {', '.join(m['stored_in'])} | {esc(m['note'])} |")
    w("")
    w("## 7. Third-party information resources (MAS-CSO-TPR)")
    w("")
    for t in rec["third_party_resources"]:
        r = res[t["resource_id"]]
        w(f"### {t['id']}: {r['name']}")
        w("")
        w(f"*{t['provider_type']}. Authorization status: {t.get('authorization_status', 'not recorded')}.*")
        w("")
        w(f"- **General usage and configuration:** {t['usage_and_configuration']}")
        w(f"- **Justification for use:** {t['justification']}")
        w(f"- **Potential impact on federal customer data:** {t['potential_impact']}")
        w("- **Mitigation measures:**")
        for m in t["mitigation_measures"]:
            w(f"  - {m}")
        w("- **Compensating controls:**")
        for c in t["compensating_controls"]:
            w(f"  - {c}")
