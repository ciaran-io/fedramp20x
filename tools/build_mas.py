    for r in by("out_conditional"):
        for c in r["conditions"]:
            w(f"| {c['id']} | {r['id']} {esc(r['name'])} | {esc(c['text'])} | {esc(c['evidence'])} |")
    w("")
    w("## 10. Open questions and decisions")
    w("")
    w("| ID | Question | Affects | Status | Decision |")
    w("|---|---|---|---|---|")
    for q in rec.get("open_questions", []):
        decided = q.get("status") == "decided"
        w(f"| {q['id']} | {esc(q['question'])} | {esc(q['affects'])} | {('Decided ' + q['decided_on']) if decided else 'Open'} | {esc(q['decision'] if decided else q['leaning'] + ' (leaning)')} |")
