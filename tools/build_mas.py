    w("## 11. Record checks")
    w("")
    n = Counter(l for l, _ in msgs)
    w(f"Last build: {n['ERROR']} errors, {n['WARN']} warnings, {n['INFO']} notes.")
    w("")
    for lvl, t in msgs:
        if lvl != "ERROR":
            w(f"- **{lvl}:** {esc(t)}")
    w("")
    return "\n".join(o)


