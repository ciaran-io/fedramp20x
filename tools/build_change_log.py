#!/usr/bin/env python3
"""Generate docs/significant-change-log.md from mas/scope-changes.json.

The scope change log is the machine-readable record (SCN-CSO-HRM). This page is the
human-readable view of the same entries, with the notice each change type needs and
the protection reviews that followed it (POL-CNA CNA-7b). Pipeline changes are counted
by change type from environment/live-state.json (POL-CMT CMT-6). Do not edit the output.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TYPE_NAMES = {"routine": "Routine recurring", "not_significant": "Not significant",
              "adaptive": "Adaptive", "transformative": "Transformative"}
NOTICE_RULES = {"routine": "Not required (SCN-RTR-NNR)", "not_significant": "Not required",
                "adaptive": "Within 10 business days after the change (SCN-ADP-NTF)",
                "transformative": "10 business days before, 5 after, and an update within 30 days (SCN-TRF-NFP, SCN-TRF-NAF, SCN-TRF-UPD)"}


def load(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def main() -> None:
    entries = load("mas/scope-changes.json").get("entries", [])
    reviews = load("environment/grc-records.json").get("protection_reviews", [])
    types = load("environment/live-state.json").get("change_events", {}).get("last_30_days", {}).get("change_types", {})
    out = [
        "# Significant change log",
        "",
        "> FICTIONAL DEMO DOCUMENT. Orrinwick Labs, Inc. is invented. Nothing here is a real security record or FedRAMP certification.",
        "> Generated by `tools/build_change_log.py` from [`mas/scope-changes.json`](../mas/scope-changes.json), the machine-readable version of this log. Do not edit.",
        "",
        "Rules: `SCN-*` in [`rules-matrix.md`](rules-matrix.md). Policy: POL-CMT CMT-5 and CMT-6, POL-CNA CNA-7b.",
        "",
        "## Changes to the scope record",
        "",
        "Every change to `mas/mas-record.json` has an entry. CI fails when the scope record changes without one.",
        "",
        "| ID | Date | Change | Resources | Change type | Notice | Notice sent | Protection review |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        kind = e.get("scn_category", "")
        reviewed = ", ".join(r["date"] for r in reviews if e["id"] in r.get("changes_reviewed", [])) or "None yet"
        sent = e.get("notification") or ("Not needed" if kind in ("routine", "not_significant") else "Not sent")
        out.append(f"| {e['id']} | {e['date']} | {e['summary']} | {', '.join(e.get('resources', []))} | "
                   f"{TYPE_NAMES.get(kind, kind)} | {NOTICE_RULES.get(kind, 'Unknown change type')} | {sent} | {reviewed} |")
    out += ["", "### Evaluations", ""]
    out += [f"- **{e['id']}:** {e.get('evaluation', '')}" for e in entries]
    out += ["", "## Pipeline changes in the last 30 days", "",
            "Every change made through the pipeline gets one of the four change types before release (POL-CMT CMT-6). "
            "Routine recurring and not significant changes are counted here, not listed. An adaptive or transformative change is also entered in the table above.",
            "", "| Change type | Changes |", "|---|---|"]
    out += [f"| {TYPE_NAMES.get(k, k)} | {v} |" for k, v in types.items()]
    (ROOT / "docs/significant-change-log.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/significant-change-log.md: {len(entries)} scope change(s)")


if __name__ == "__main__":
    main()
