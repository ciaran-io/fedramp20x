#!/usr/bin/env python3
"""Render the policy set from policies/policy-set.json.

Writes docs/policies/POL-*.md, docs/policies-index.md and evidence/policies.json.
Fails if a requirement names an unknown KSI or scope resource, or if any KSI
in the registry is not covered by a policy requirement.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICE = "> FICTIONAL DEMO DOCUMENT. Orrinwick Labs, Inc. is invented. Nothing here is a real security record or FedRAMP certification. Generated by `tools/build_policies.py` from `policies/policy-set.json`; do not edit."


def main() -> int:
    ps = json.loads((ROOT / "policies/policy-set.json").read_text())
    reg = json.loads((ROOT / "evidence/ksi-registry.json").read_text())
    latest = json.loads((ROOT / "evidence/latest.json").read_text())
    mas = json.loads((ROOT / "mas/mas-record.json").read_text())

    ksis = {k["id"][4:]: k for k in reg["indicators"]}
    live = {k["id"][4:]: k for k in latest["ksis"]}
    res = {r["id"]: r for r in mas["information_resources"]}
    errors, covered = [], set()

    out_dir = ROOT / "docs/policies"
    out_dir.mkdir(exist_ok=True)
    index_rows, api = [], []

    for p in ps["policies"]:
        for rid in p["resources"]:
            if rid not in res:
                errors.append(f"{p['id']}: unknown resource {rid}")
        ptheme = [k for k in ksis if ksis[k]["theme"] == p["theme"]]
        pcovered = set()
        for rq in p["requirements"]:
            for k in rq["ksis"]:
                if k not in ksis:
                    errors.append(f"{p['id']} {rq['id']}: unknown KSI {k}")
                else:
                    pcovered.add(k)
        covered |= pcovered
        missing = [k for k in ptheme if k not in pcovered]
        if missing:
            errors.append(f"{p['id']}: KSIs without a requirement: {', '.join(missing)}")

        L = [f"# {p['title']} ({p['id']})", "", NOTICE, "",
             "| | |", "|---|---|",
             f"| Owner | {p['owner']} |", f"| Approver | {ps['approver']} |",
             (f"| Version | {p['approval']['version']}, approved by the {p['approval']['approved_by']} on {p['approval']['date']} |"
              if p.get("approval") else f"| Version | {ps['version']} draft, effective {ps['effective']} |"),
             f"| Review cadence | {p['review_cadence']} |",
             f"| Theme | {p['theme']}: {next(t['name'] for t in reg['themes'] if t['key'] == p['theme'])} |", "",
             "## Purpose", "", p["purpose"], "",
             "## Scope", "", ps["general"]["applies_to"], "",
             "This policy covers these information resources from the scope record:", "",
             "| ID | Resource |", "|---|---|"]
        L += [f"| {r} | {res[r]['name']} |" for r in p["resources"] if r in res]
        L += ["", "## Requirements", "", "| ID | Requirement | KSIs |", "|---|---|---|"]
        L += [f"| {rq['id']} | {rq['text']} | {', '.join('KSI-' + k for k in rq['ksis']) or rq.get('ksis_note', 'none')} |" for rq in p["requirements"]]
        L += ["", "## Indicators and validation", "",
              "| KSI | Name | Automated methods | Current status |", "|---|---|---|---|"]
        kapi = []
        for k in ptheme:
            lv = live.get(k, {})
            methods = [m["method_id"] for m in lv.get("methods", [])]
            status = lv.get("status", "not_implemented")
            L.append(f"| KSI-{k} | {ksis[k]['name']} | {', '.join('`'+m+'`' for m in methods) or 'none yet'} | {status} |")
            kapi.append({"ksi": f"KSI-{k}", "methods": methods, "status": status})
        L += ["", "Status is a simulated validator result. Class C needs at least two automated methods per KSI (`FRC-CSX-VVK`).", "",
              "## Exceptions", "", ps["general"]["exceptions"], "",
              "## Enforcement", "", ps["general"]["enforcement"], ""]
        (out_dir / f"{p['id']}.md").write_text("\n".join(L))
        index_rows.append((p, len(ptheme), len([k for k in kapi if k['status'] == 'pass'])))
        api.append({"id": p["id"], "title": p["title"], "theme": p["theme"], "owner": p["owner"],
                    "review_cadence": p["review_cadence"], "version": ps["version"], "effective": ps["effective"],
                    "document": f"documents/policies/{p['id']}.md", "resources": p["resources"],
                    "requirements": [{"id": r["id"], "text": r["text"], "ksis": [f"KSI-{k}" for k in r["ksis"]]} for r in p["requirements"]],
                    "indicators": kapi})

    for k in ksis:
        if k not in covered:
            errors.append(f"KSI-{k} is not covered by any policy requirement")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    I = ["# Policy index", "", NOTICE, "",
         f"Version {ps['version']}, effective {ps['effective']}. Approver: {ps['approver']}. Generated from `policies/policy-set.json`. Do not edit this file by hand.", "",
         "| Policy | Theme | Owner | Review | KSIs | KSIs passing |", "|---|---|---|---|---|---|"]
    I += [f"| [{p['title']}](policies/{p['id']}.md) | {p['theme']} | {p['owner']} | {p['review_cadence']} | {n} | {ok} |" for p, n, ok in index_rows]
    I += ["", f"All {len(ksis)} KSIs in the Class C registry map to at least one policy requirement. Policy text states what the company requires. Validator status states what the simulated checks observe.", ""]
    (ROOT / "docs/policies-index.md").write_text("\n".join(I))
    (ROOT / "evidence/policies.json").write_text(json.dumps({"demo_notice": ps["_notice"], "version": ps["version"], "effective": ps["effective"], "policies": api}, indent=2))
    print(f"policies built: {len(api)} policies, {len(covered)} KSIs covered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
